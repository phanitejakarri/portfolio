import { useEffect, useRef, useState } from "react";
import { ArrowUpRight } from "lucide-react";
import type { GitDiagram } from "@/gitdiagrams";
import { ghRepo, gitdiagramUrl } from "@/lib/github";

let seq = 0;

// Renders a project's GitDiagram (Mermaid) in a GitDiagram-style card. Mermaid is
// loaded on demand so it stays out of the main bundle.
export default function GitDiagramView({ repo, diagram }: { repo: string; diagram: GitDiagram }) {
  const host = useRef<HTMLDivElement>(null);
  const [state, setState] = useState<"loading" | "ready" | "error">("loading");

  useEffect(() => {
    let cancelled = false;
    setState("loading");
    Promise.all([import("mermaid"), import("@mermaid-js/layout-elk"), document.fonts.ready])
      .then(async ([{ default: mermaid }, { default: elkLayouts }]) => {
        mermaid.registerLayoutLoaders(elkLayouts);
        mermaid.initialize({
          layout: "elk",
          htmlLabels: false,
          startOnLoad: false,
          securityLevel: "loose",
          theme: "base",
          themeVariables: {
            fontFamily: "Archivo, system-ui, sans-serif",
            fontSize: "14px",
            lineColor: "#1f1f1f",
            primaryTextColor: "#0f172a",
            clusterBkg: "#f7f5fb",
            clusterBorder: "#d9d2e9",
            edgeLabelBackground: "#f3e8ff",
          },
          flowchart: { curve: "step", padding: 14, nodeSpacing: 36, rankSpacing: 56, htmlLabels: false },
        });
        const { svg } = await mermaid.render(`gd-${repo.replace(/\W/g, "")}-${++seq}`, diagram.code);
        if (cancelled || !host.current) return;
        host.current.innerHTML = svg;
        const el = host.current.querySelector("svg");
        if (el) {
          // natural size; wide diagrams scroll sideways instead of shrinking to unreadable
          const w = el.viewBox.baseVal.width;
          el.style.maxWidth = "none";
          el.style.width = `${Math.min(w, 1500)}px`;
          el.style.height = "auto";
          el.removeAttribute("height");
        }
        host.current.querySelectorAll("a").forEach((a) => {
          a.setAttribute("target", "_blank");
          a.setAttribute("rel", "noopener noreferrer");
        });
        setState("ready");
      })
      .catch(() => !cancelled && setState("error"));
    return () => {
      cancelled = true;
    };
  }, [repo, diagram]);


  return (
    <div className="rounded-2xl border-2 border-[#1f1f1f] bg-[#f3e8ff] text-[#1f1f1f] shadow-[6px_6px_0_#1f1f1f] overflow-hidden">
      <div className="flex flex-wrap items-center justify-between gap-3 px-4 md:px-6 py-3 border-b-2 border-[#1f1f1f] bg-[#ead9ff]">
        <span className="font-semibold text-[15px]">
          Git<span className="text-[#9333ea]">Diagram</span>
          <span className="font-normal text-[#1f1f1f]/60 ml-3 font-mono text-[12px]">
            {ghRepo(repo).toLowerCase()}
          </span>
        </span>
        <span className="flex items-center gap-3">
          <span className="font-mono text-[11px] uppercase tracking-[0.1em] text-[#1f1f1f]/60">
            {diagram.generated ? "Generated by GitDiagram" : "GitDiagram format"}
          </span>
          <a
            href={gitdiagramUrl(repo)}
            target="_blank"
            rel="noopener noreferrer"
            className="inline-flex items-center gap-1 rounded-md border-2 border-[#1f1f1f] bg-[#c084fc] px-2.5 py-1 text-[13px] font-semibold shadow-[2px_2px_0_#1f1f1f] hover:translate-x-[1px] hover:translate-y-[1px] hover:shadow-[1px_1px_0_#1f1f1f] transition-all"
          >
            Open <ArrowUpRight size={14} />
          </a>
        </span>
      </div>
      <div className="overflow-x-auto" data-lenis-prevent-horizontal>
        <div ref={host} className="gd-host w-max min-w-full px-4 md:px-8 py-8 flex justify-center" />
        {state === "loading" && <div className="py-24 text-center font-mono text-[12px] text-[#1f1f1f]/50">Drawing diagram…</div>}
        {state === "error" && <div className="py-24 text-center font-mono text-[12px] text-[#1f1f1f]/60">Couldn&apos;t render this diagram.</div>}
      </div>
      <div className="px-4 md:px-6 py-2.5 border-t-2 border-[#1f1f1f]/10 font-mono text-[11px] text-[#1f1f1f]/55">
        Click any box to open its file on GitHub · scroll sideways on wide diagrams
      </div>
    </div>
  );
}
